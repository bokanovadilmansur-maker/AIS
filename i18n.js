  dict.en = {};
  const textEls = document.querySelectorAll('[data-i18n]');
  const attrEls = document.querySelectorAll('[data-i18n-attr]');
  textEls.forEach((el) => {
    const k = el.dataset.i18n;
    if (!(k in dict.en)) dict.en[k] = el.innerHTML.trim();
  });
  attrEls.forEach((el) => el.dataset.i18nAttr.split(';').forEach((pair) => {
    const [attr, k] = pair.split(':');
    if (!(k in dict.en)) dict.en[k] = el.getAttribute(attr) || '';
  }));
  const metaDesc = document.querySelector('meta[name="description"]');
  dict.en['meta.desc'] = metaDesc.content;
  LANGS.forEach((l) => Object.assign(dict[l], extra[l]));

  let current = 'en';
  const t = (key, vars) => {
    let s = dict[current][key] ?? dict.en[key] ?? key;
    if (vars) s = s.replace(/\{(\w+)\}/g, (_, v) => vars[v] ?? '');
    return s;
  };

  const listeners = [];
  const apply = (lang) => {
    if (!LANGS.includes(lang)) lang = 'en';
    current = lang;
    textEls.forEach((el) => { el.innerHTML = t(el.dataset.i18n); });
    attrEls.forEach((el) => el.dataset.i18nAttr.split(';').forEach((pair) => {
      const [attr, k] = pair.split(':');
      el.setAttribute(attr, t(k));
    }));
    document.documentElement.lang = lang;
    document.title = t('meta.title');
    metaDesc.content = t('meta.desc');
    document.querySelectorAll('[data-lang]').forEach((b) => b.setAttribute('aria-pressed', String(b.dataset.lang === lang)));
    try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) { /* storage unavailable */ }
    listeners.forEach((fn) => fn(lang));
  };

